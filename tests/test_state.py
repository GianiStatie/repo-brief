def build() -> Path:
    root = Path(tempfile.mkdtemp(prefix="repo-brief-state-"))
    for rel, text in FILES.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    subprocess.run(["git", "init", "-q"], cwd=root, check=True)
    subprocess.run(["git", "add", "-A"], cwd=root, check=True)
    subprocess.run(
        ["git", "-c", "user.email=a@b", "-c", "user.name=a", "commit", "-qm", "init"],
        cwd=root,
        check=True,
    )
    return root


class TrustTest(unittest.TestCase):
    def setUp(self):
        self.config = tempfile.mkdtemp(prefix="repo-brief-config-")
        self.addCleanup(lambda: os.environ.pop("REPO_BRIEF_CONFIG_DIR", None))
        os.environ["REPO_BRIEF_CONFIG_DIR"] = self.config
        self.root = build()

    def test_trust_round_trip(self):
        self.assertFalse(trust.is_trusted(self.root))
        trust.trust(self.root)
        self.assertTrue(trust.is_trusted(self.root))
        trust.untrust(self.root)
        self.assertFalse(trust.is_trusted(self.root))

    def test_trust_is_machine_local_not_in_the_repo(self):
        trust.trust(self.root)
        self.assertTrue((Path(self.config) / "trust.json").is_file())
        self.assertFalse((self.root / ".repo-brief" / "trust.json").exists())

    def test_the_adapter_loads_without_trust(self):
        (self.root / "tools/brief_adapter.py").write_text(
            "from repobrief.adapters.generic import GenericAdapter\n\n\n"
            "class Adapter(GenericAdapter):\n    name = 'custom'\n",
            encoding="utf-8",
        )
        self.assertFalse(trust.is_trusted(self.root))
        self.assertEqual(cli.load_adapter(self.root).name, "custom")

    def test_only_scripts_in_a_script_folder_of_this_repo_may_run(self):
        def runnable(kind, path):
            return catalog.runnable(self.root, {"kind": kind, "path": path})

        self.assertEqual(runnable("script", "tools/check_docs.py"), "")
        self.assertIn("not in a script folder", runnable("script", "docs/index.md"))
        self.assertIn("outside the repository", runnable("script", "../escape.py"))
        self.assertIn("does not exist", runnable("script", "tools/missing.py"))
        self.assertEqual(runnable("make", "Makefile"), "")
        (self.root / "docs/dev.sh").write_text("#!/bin/sh\n", encoding="utf-8")
        self.assertIn("not the repo's dev.sh", runnable("devsh", "docs/dev.sh"))

    def test_a_local_repo_has_its_own_script_folder(self):
        state = self.root / ".repo-brief"
        (state / "tools").mkdir(parents=True)
        (state / "tools" / "probe.py").write_text('"""Read a thing."""\n', encoding="utf-8")
        self.assertIn("not in a script folder", catalog.runnable(
            self.root, {"kind": "script", "path": ".repo-brief/tools/probe.py"}
        ))
        (state / "local.json").write_text('{"include": ["docs/meta"]}\n', encoding="utf-8")
        self.assertEqual(catalog.runnable(
            self.root, {"kind": "script", "path": ".repo-brief/tools/probe.py"}
        ), "")


class CatalogTest(unittest.TestCase):
    def setUp(self):
        self.root = build()
        self.detected = GenericAdapter().detected(self.root)

    def scanned(self):
        return {item["id"]: item for item in catalog.scan(self.root, self.detected)}

    def test_groups_follow_what_a_script_does(self):
        groups = {key: item["group"] for key, item in self.scanned().items()}
        self.assertEqual(groups["script:tools/check_docs.py"], "inspect")
        self.assertEqual(groups["script:tools/rush_bench.py"], "dev")
        self.assertEqual(groups["script:scripts/train_stand.py"], "dev")
        self.assertEqual(groups["script:tools/diagnose_stand.py"], "debug")
        self.assertEqual(groups["script:tools/generate_icons.py"], "manual")
        self.assertEqual(groups["script:tools/fetch_dossiers.py"], "manual")
        self.assertEqual(groups["script:tools/copy_diary.py"], "manual")
        self.assertEqual(groups["devsh:test"], "dev")
        self.assertEqual(groups["devsh:export"], "dev")
        self.assertEqual(groups["make:test"], "dev")
        self.assertEqual(groups["make:release"], "manual")
        self.assertEqual(groups["make:doctor"], "manual")

    def test_a_helper_module_is_not_a_script(self):
        self.assertNotIn("script:tools/lib/common.py", self.scanned())
        self.assertNotIn("script:tools/lib/arena.py", self.scanned())

    def test_a_script_is_judged_with_the_repo_modules_it_imports(self):
        item = self.scanned()["script:tools/fight_dio.py"]
        self.assertEqual(item["group"], "dev")
        self.assertIn("runs Godot", item["evidence"])
        # A socket to the game it started is not the network.
        self.assertFalse(any("network" in line for line in item["evidence"]))

    def test_the_evidence_says_why(self):
        found = self.scanned()
        self.assertEqual(found["script:tools/check_docs.py"]["evidence"], ["reads only"])
        self.assertIn("runs Godot", found["script:tools/rush_bench.py"]["evidence"])
        self.assertIn("uses the network (urllib.request)", found["script:tools/fetch_dossiers.py"]["evidence"])
        self.assertIn("reads a secret (SPEEDWAGON_PASSWORD)", found["script:tools/copy_diary.py"]["evidence"])
        self.assertIn("uses a training library (torch)", found["script:scripts/train_stand.py"]["evidence"])

    def test_a_script_for_another_runtime_is_unclear(self):
        item = self.scanned()["script:tools/awaken_stand.py"]
        self.assertEqual(item["group"], "manual")
        self.assertIn("calls pierce_with_arrow, summon_stand, which it never defines or imports", item["evidence"])

    def test_a_word_never_makes_a_script_look_safer(self):
        item = self.scanned()["script:tools/check_cache.py"]
        self.assertEqual(item["group"], "manual")
        self.assertIn("writes files (open('w'))", item["evidence"])

    def test_args_are_read_from_argparse(self):
        self.assertIn("--strict", self.scanned()["script:tools/check_docs.py"]["args"])

    def test_a_choice_survives_a_rescan_and_new_scripts_are_named(self):
        path, data, added = catalog.write(self.root, self.detected)
        self.assertTrue(path.is_file())
        self.assertEqual(len(added), len(data["detected"]))
        catalog.set_group(self.root, "script:tools/check_docs.py", "manual")
        (self.root / "tools/list_stands.py").write_text(
            '"""List the stands."""\n\nif __name__ == "__main__":\n    print(3)\n', encoding="utf-8"
        )
        detected = GenericAdapter().detected(self.root)
        _path, data, added = catalog.write(self.root, detected)
        found = {item["id"]: item for item in data["detected"]}
        self.assertEqual(found["script:tools/check_docs.py"]["group"], "manual")
        self.assertEqual(found["script:tools/check_docs.py"]["guess"], "inspect")
        self.assertEqual(data["choices"], {"script:tools/check_docs.py": "manual"})
        self.assertEqual([item["id"] for item in added], ["script:tools/list_stands.py"])

    def test_a_first_layout_file_keeps_its_judgements(self):
        state = self.root / ".repo-brief"
        state.mkdir(exist_ok=True)
        (state / "tools.json").write_text(json.dumps({
            "generated": True,
            "groups": {"dev": {"exposed": True, "ask": False}},
            "judgments": {"script:tools/check_docs.py": "manual"},
            "commands": [{"id": "script:tools/check_docs.py", "group": "manual"}],
        }), encoding="utf-8")
        _path, data, _added = catalog.write(self.root, self.detected)
        self.assertEqual(data["choices"], {"script:tools/check_docs.py": "manual"})
        self.assertNotIn("commands", data)
        self.assertNotIn("judgments", data)

    def test_the_script_folders_are_a_choice(self):
        state = self.root / ".repo-brief"
        state.mkdir(exist_ok=True)
        (state / "tools.json").write_text(json.dumps({"folders": ["scripts"]}), encoding="utf-8")
        _path, data, _added = catalog.write(self.root, self.detected)
        ids = {item["id"] for item in data["detected"]}
        self.assertIn("script:scripts/train_stand.py", ids)
        self.assertNotIn("script:tools/check_docs.py", ids)
        self.assertIn("not in a script folder", catalog.runnable(
            self.root, {"kind": "script", "path": "tools/check_docs.py"}
        ))

    def test_the_rules_then_the_narrowing(self):
        self.assertFalse({"manual"} & catalog.allowed_groups(True, narrowed=set(catalog.GROUPS)))
        self.assertEqual(catalog.allowed_groups(False), {"brief"})
        self.assertEqual(catalog.allowed_groups(True), {"brief", "inspect", "dev", "debug"})
        self.assertEqual(
            catalog.allowed_groups(True, narrowed={"brief", "inspect"}), {"brief", "inspect"}
        )


class OverviewTest(unittest.TestCase):
    def setUp(self):
        self.root = build()
        self.adapter = GenericAdapter()
        self.detected = self.adapter.detected(self.root)
        self.units = self.adapter.units(self.root)

    def test_it_names_the_facts_and_keeps_the_written_half(self):
        path, _ = overview.write(self.root, self.adapter, self.detected, self.units)
        text = path.read_text(encoding="utf-8")
        self.assertIn("## Summary", text)
        self.assertIn("## Stack", text)
        self.assertIn("## Areas", text)
        self.assertIn("docs/meta/decisions.md", text)
        self.assertIn(overview.PLACEHOLDER, text)
        written = "%s\nThis game teaches timing.\n%s" % (overview.WRITTEN_START, overview.WRITTEN_END)
        path.write_text(text.replace(overview.PLACEHOLDER, written), encoding="utf-8")
        overview.write(self.root, self.adapter, self.detected, self.units)
        self.assertIn("This game teaches timing.", path.read_text(encoding="utf-8"))
        self.assertEqual(overview.written(self.root), "This game teaches timing.")

    def test_an_earlier_placeholder_makes_way_for_this_one(self):
        path, _ = overview.write(self.root, self.adapter, self.detected, self.units)
        earlier = "%s\n_Not written yet. An agent with a runner fills this section._\n%s" % (
            overview.WRITTEN_START, overview.WRITTEN_END
        )
        path.write_text(path.read_text(encoding="utf-8").replace(overview.PLACEHOLDER, earlier), encoding="utf-8")
        self.assertEqual(overview.written(self.root), "")
        overview.write(self.root, self.adapter, self.detected, self.units)
        self.assertIn(overview.PLACEHOLDER, path.read_text(encoding="utf-8"))

    def test_the_prompt_names_the_markers_and_the_limit(self):
        for part in (overview.WRITTEN_START, overview.WRITTEN_END, str(overview.WRITE_LIMIT)):
            self.assertIn(part, overview.PROMPT)


class IndexTest(unittest.TestCase):
    def setUp(self):
        self.root = build()
        self.adapter = GenericAdapter()
        self.addCleanup(lambda: index.Index(self.root).close())

    def test_it_is_off_until_asked_for(self):
        units, state, stats = index.ensure(self.root, self.adapter)
        self.assertIsNone(state)
        self.assertEqual(stats, {})
        self.assertFalse(index.enabled(self.root))
        self.assertTrue(units)

    def test_units_match_the_unindexed_walk(self):
        units, state, stats = index.ensure(self.root, self.adapter, build=True)
        try:
            full = {unit.path: unit.kind for unit in GenericAdapter().units(self.root)}
            fast = {unit.path: unit.kind for unit in units}
            self.assertEqual(fast, full)
            self.assertIn("godot/src/net/Stub.java", fast)
            self.assertGreater(stats["parsed"], 0)
        finally:
            state.close()

    def test_only_a_changed_file_is_parsed_again(self):
        units, state, _ = index.ensure(self.root, self.adapter, build=True)
        state.close()
        target = self.root / "godot/src/player.gd"
        target.write_text(target.read_text(encoding="utf-8") + "\n# note\n", encoding="utf-8")
        _units, state, stats = index.ensure(self.root, self.adapter)
        try:
            self.assertEqual(stats["parsed"], 1)
            self.assertGreater(stats["kept"], 0)
        finally:
            state.close()

    def test_an_older_file_is_replaced_not_reused(self):
        _units, state, _ = index.ensure(self.root, self.adapter, build=True)
        state.conn.execute("UPDATE meta SET value = '1/old' WHERE key = 'version'")
        state.conn.commit()
        state.close()
        state = index.Index(self.root).connect()
        try:
            self.assertEqual(state.counts()["files"], 0)
        finally:
            state.close()

    def test_creating_it_keeps_it_out_of_git(self):
        _units, state, _ = index.ensure(self.root, self.adapter, build=True)
        state.close()
        ignore = (self.root / ".repo-brief" / ".gitignore").read_text(encoding="utf-8")
        self.assertIn("index.sqlite*", ignore)
        status = subprocess.run(
            ["git", "status", "--porcelain", "--untracked-files=all"],
            cwd=self.root,
            capture_output=True,
            text=True,
            check=True,
        ).stdout
        self.assertNotIn("index.sqlite", status)

    def test_camel_case_words_are_indexed(self):
        self.assertIn("hermit", index.words_for("HermitPurple"))
        self.assertIn("purple", index.words_for("HermitPurple"))

    def test_words_are_counted_with_their_pieces(self):
        counts = index.word_counts("getStarFinger(); getStarFinger(); stop_time")
        self.assertEqual(
            (counts["getstarfinger"], counts["star"], counts["stop"], counts["time"]), (2, 2, 1, 1)
        )

    def test_digit_runs_and_singulars_are_counted_too(self):
        self.assertTrue({"stand2user", "stand", "2", "user"} <= index.words_for("stand2user"))
        counts = index.word_counts("Stands; Stand; getAbilities")
        self.assertEqual((counts["stands"], counts["stand"], counts["ability"]), (1, 2, 1))

    def test_the_fold_leaves_words_that_are_rarely_plurals(self):
        folded = [index.fold(word) for word in ("stands", "stories", "status", "boss", "axis", "arms")]
        self.assertEqual(folded, ["stand", "story", "status", "boss", "axis", "arms"])

    def test_a_file_no_parser_reads_is_counted_but_stays_path_only(self):
        (self.root / "godot" / "stands.cfg").write_text("menacing = true\n", encoding="utf-8")
        units, state, _ = index.ensure(self.root, self.adapter, build=True)
        try:
            self.assertIn("godot/stands.cfg", state.paths_with_word("menacing"))
            unit = next(unit for unit in units if unit.path == "godot/stands.cfg")
            self.assertEqual((unit.kind, unit.text, unit.words), ("file", "", []))
        finally:
            state.close()

    def test_candidate_lookup_is_word_or_prefix(self):
        _units, state, _ = index.ensure(self.root, self.adapter, build=True)
        try:
            self.assertIn("godot/src/player.gd", state.candidate_paths(["play"]))
            self.assertNotIn("godot/src/player.gd", state.candidate_paths(["xyzzy"]))
            self.assertIn("godot/src/player.gd", state.paths_with_word("player"))
            self.assertNotIn("godot/src/player.gd", state.paths_with_word("play"))
        finally:
            state.close()


class LogTest(unittest.TestCase):
    def setUp(self):
        self.data = tempfile.mkdtemp(prefix="repo-brief-data-")
        self.addCleanup(lambda: os.environ.pop("REPO_BRIEF_DATA_DIR", None))
        os.environ["REPO_BRIEF_DATA_DIR"] = self.data
        self.root = build()

    def test_nothing_is_recorded_until_it_is_enabled(self):
        self.assertIsNone(log.record_ask(self.root, "what moves the player?", "a script"))
        self.assertFalse(log.enabled(self.root))
        self.assertFalse(log.path_for(self.root).exists())
        self.assertEqual(log.recent(self.root), [])

    def test_an_enabled_log_keeps_the_ask_and_its_calls_outside_the_repo(self):
        log.enable(self.root)
        ask_id = log.record_ask(
            self.root,
            "what moves the player?",
            "a script",
            session_id="ses_1",
            model="fake",
            duration_ms=1200,
            cost_usd=0.001,
            client="cli",
            runner="claude",
            turns=3,
            references=[{"path": "godot/src/player.gd", "lines": "1-6", "note": "the class"}],
            calls=[{"tool": "Grep", "input": {"pattern": "move"}, "result_bytes": 40}],
        )
        self.assertIsNotNone(ask_id)
        recent = log.recent(self.root)
        self.assertEqual(recent[0]["question"], "what moves the player?")
        self.assertEqual(recent[0]["session_id"], "ses_1")
        self.assertEqual(recent[0]["turns"], 3)
        calls = log.calls_for(self.root, ask_id)
        self.assertEqual(calls[0]["tool"], "Grep")
        self.assertIn("move", calls[0]["input"])
        self.assertFalse(str(log.path_for(self.root)).startswith(str(self.root)))
        summary = log.summary(self.root)
        self.assertEqual((summary["asks"], summary["calls"]), (1, 1))
        self.assertAlmostEqual(summary["cost_usd"], 0.001)

    def test_a_first_version_log_gains_the_new_columns(self):
        import sqlite3

        target = log.path_for(self.root)
        target.parent.mkdir(parents=True, exist_ok=True)
        with sqlite3.connect(str(target)) as conn:
            conn.execute(
                "CREATE TABLE asks (id INTEGER PRIMARY KEY, at TEXT NOT NULL, repo TEXT NOT NULL, "
                "question TEXT NOT NULL, answer TEXT NOT NULL, session_id TEXT, model TEXT, "
                "duration_ms INTEGER, cost_usd REAL, status TEXT)"
            )
        self.assertIsNotNone(log.record_ask(self.root, "q", "a", client="cli"))
        self.assertEqual(log.recent(self.root)[0]["client"], "cli")


class InitTest(unittest.TestCase):
    def setUp(self):
        self.config = tempfile.mkdtemp(prefix="repo-brief-config-")
        self.addCleanup(lambda: os.environ.pop("REPO_BRIEF_CONFIG_DIR", None))
        os.environ["REPO_BRIEF_CONFIG_DIR"] = self.config
        self.root = build()

    def run_cli(self, *argv):
        out = io.StringIO()
        with redirect_stdout(out):
            code = cli.main(["--root", str(self.root), *argv])
        self.assertEqual(code, 0, out.getvalue())
        return out.getvalue()

    def test_search_prints_the_files_and_their_lines(self):
        found = json.loads(self.run_cli("search", "--json", "summon_stand"))
        self.assertEqual(found["results"][0]["path"], "tools/awaken_stand.py")
        self.assertEqual(found["results"][0]["lines"], [{"line": 2, "text": "summon_stand('star_platinum')"}])
        self.assertIn("1. tools/awaken_stand.py", self.run_cli("search", "summon_stand"))

    def test_overview_prompt_prints_the_instructions(self):
        self.assertIn(overview.WRITTEN_START, self.run_cli("overview", "--prompt"))

    def test_local_init_writes_nothing_into_git(self):
        self.run_cli("init", "--local", "--trust")
        self.assertTrue((self.root / ".repo-brief" / "adapter.py").is_file())
        self.assertTrue((self.root / ".repo-brief" / "map.md").is_file())
        self.assertTrue((self.root / ".repo-brief" / "overview.md").is_file())
        self.assertTrue((self.root / ".repo-brief" / "tools.json").is_file())
        marker = json.loads((self.root / ".repo-brief" / "local.json").read_text())
        self.assertIn("docs/meta", marker["include"])
        status = subprocess.run(
            ["git", "status", "--porcelain", "--untracked-files=all"],
            cwd=self.root,
            capture_output=True,
            text=True,
            check=True,
        ).stdout
        self.assertNotIn(".repo-brief/", status)
