"""The zero-configuration adapter.

Runs on any repository before it has an adapter of its own. Everything it does
is derived from `detect()`; the repo-specific adapter that `scaffold` writes is
a thin override of the parts a machine cannot guess.
"""
from __future__ import annotations

import re
from pathlib import Path

from ..cache import ParseCache
from ..contract import Adapter, Item, Source, Unit
from ..detect import CAPTURE_DIR, NOTES_DOC, SKIP_DIRS, WRITING_DOC, detect, is_archived
from ..parsers import PARSERS, parse_generic, resolve

DECISION_HEAD_RE = re.compile(r"^# ((?:D|ADR)-\d+|\d{4}) — (.+)$", re.M)
DATED_HEAD_RE = re.compile(r"^## (\d{4}-\d{2}-\d{2}) — (.+)$", re.M)
RULE_LINE_RE = re.compile(r"^\*\*(?:Rule|Contract|Status)\.\*\*", re.M)
FRONTMATTER_RE = re.compile(r"\A---\n(.*?)\n---\n", re.S)

BOX_RE = re.compile(r"^- \[ \] (.+)$")
SECTION_RE = re.compile(r"^##+ (.+)$")
TABLE_SEPARATOR_RE = re.compile(r"^:?-{2,}:?$")
TABLE_HEADERS = {"#", "id", "task", "item", "name", "sprint", "date", "milestone"}
DONE_RE = re.compile(r"\b(done|implemented|complete[d]?|resolved|shipped|closed)\b", re.I)
OPEN_RE = re.compile(r"\b(open|partial|in progress|blocking|pending|todo|wip|active|paused)\b", re.I)

SOURCE_GLOBS = ("docs/**/*.md", "*.md", "tools/*.py", "scripts/*.py", ".github/workflows/*.yml", ".github/workflows/*.yaml")
MAX_SOURCE_BYTES = 512 * 1024

BINARY_EXTS = {
    ".png", ".jpg", ".jpeg", ".gif", ".webp", ".ico", ".svg", ".woff", ".woff2",
    ".ttf", ".otf", ".mp3", ".ogg", ".wav", ".zip", ".tar", ".gz", ".pdf", ".exe",
    ".dll", ".so", ".dylib", ".class", ".jar", ".pyc", ".lock",
    ".aseprite", ".psd", ".blend", ".fbx", ".glb", ".obj", ".ktx", ".exr", ".tga",
    ".import", ".uid",
}

# A file that announces itself as generated should never be ranked or indexed:
# it is a copy of something else, and matching it means citing a copy. Some
# stubs say "This file was auto-generated from <schema>"; a bare "auto-generated"
# would also match a doc that merely talks about generated content.
GENERATED_MARKERS = (
    "generated by", "do not edit by hand", "generated file", "code generated",
    "this file was auto-generated",
)


def is_generated(text: str) -> bool:
    head = "\n".join(text.splitlines()[:5]).lower()
    return any(marker in head for marker in GENERATED_MARKERS)



def _frontmatter(text: str) -> dict:
    match = FRONTMATTER_RE.match(text)
    if not match:
        return {}
    data = {}
    for line in match.group(1).splitlines():
        if ":" not in line:
            continue
        key, value = line.split(":", 1)
        value = value.strip()
        if value.startswith("[") and value.endswith("]"):
            data[key.strip()] = [v.strip() for v in value[1:-1].split(",") if v.strip()]
        else:
            data[key.strip()] = value
    return data


def _line_of(text: str, offset: int) -> int:
    return text.count("\n", 0, offset) + 1


class GenericAdapter(Adapter):
    name = "generic"
    # Generated trees this repo's adapter wants skipped everywhere, including
    # `detect()`. Subclasses widen it; the default is the shared set.
    skip_dirs = SKIP_DIRS

    def __init__(self) -> None:
        self._detected = None
        self._units = None

    def detected(self, root: Path):
        if self._detected is None:
            self._detected = detect(root, skip_dirs=self.skip_dirs)
        return self._detected

    def units(self, root: Path) -> list[Unit]:
        if self._units is not None:
            return self._units
        detected = self.detected(root)
        excluded = self.excluded(root)
        archived = self.archived(root)
        claimed = self._claimed_paths(root, detected)
        # Detection already walked the tree; walking a large tree again
        # costs half a second. Parsed units come first, in walk order, as they
        # always have. A file is read through the cache, then resolved against
        # the tree as it is now.
        cache = ParseCache(root)
        parsed, generic = [], []
        for relative in detected.files:
            rel = relative.as_posix()
            if rel in claimed or rel in excluded:
                continue
            path = root / relative
            suffix = path.suffix.lower()
            reader = PARSERS.get(suffix)
            unit = cache.read(reader, path, rel) if reader else None
            if unit is not None and not is_generated(unit.text):
                parsed.append(resolve(root, unit))
            elif suffix not in BINARY_EXTS:
                generic.append(parse_generic(root, path))
        cache.save()
        units = parsed + generic
        for unit in units:
            if is_archived(unit.path, archived):
                unit.kind = "archive"
        self._units = units
        return units

    def _claimed_paths(self, root: Path, detected) -> set[str]:
        """Files that belong to another layer and must not also rank as units."""
        claimed = set()
        if detected.decisions_dir:
            folder = root / detected.decisions_dir
            claimed.update(p.relative_to(root).as_posix() for p in folder.glob("*.md"))
        if detected.decisions_file:
            claimed.add(detected.decisions_file)
        return claimed

    def decisions(self, root: Path) -> list[Item]:
        detected = self.detected(root)
        if detected.decisions_dir:
            return self._from_directory(root, root / detected.decisions_dir)
        if detected.decisions_file:
            return self._from_file(root, root / detected.decisions_file)
        return []

    def _from_directory(self, root: Path, folder: Path) -> list[Item]:
        items = []
        walked = self.detected(root).paths
        for path in sorted(folder.glob("*.md")):
            if path.relative_to(root).as_posix() not in walked:
                continue  # a gitignored draft is not a decision anyone else can see
            text = path.read_text(encoding="utf-8", errors="replace")
            for match in DECISION_HEAD_RE.finditer(text):
                meta = _frontmatter(text)
                rule = RULE_LINE_RE.search(text, match.end())
                items.append(
                    Item(
                        path=path.relative_to(root).as_posix(),
                        line=_line_of(text, rule.start()) if rule else _line_of(text, match.start()),
                        text=match.group(2).strip(),
                        body=text[match.start():],
                        kind="decision",
                        group=meta.get("area", ""),
                        date=meta.get("date", ""),
                        label=match.group(1),
                    )
                )
                break
        return items

    def _from_file(self, root: Path, path: Path) -> list[Item]:
        text = path.read_text(encoding="utf-8", errors="replace")
        rel = path.relative_to(root).as_posix()
        items = []
        matches = list(DATED_HEAD_RE.finditer(text))
        for position, match in enumerate(matches):
            end = matches[position + 1].start() if position + 1 < len(matches) else len(text)
            body = text[match.start():end]
            rule = RULE_LINE_RE.search(body)
            items.append(
                Item(
                    path=rel,
                    line=_line_of(text, match.start() + (rule.start() if rule else 0)),
                    text=match.group(2).strip(),
                    body=body,
                    kind="decision",
                    date=match.group(1),
                    # A single-file log has no per-entry filename to cite; the
                    # date is what distinguishes one entry from the next.
                    label=match.group(1),
                )
            )
        return items

    def open_work(self, root: Path) -> list[Item]:
        detected = self.detected(root)
        items = []
        for rel in detected.open_work:
            path = root / rel
            if not path.is_file():
                continue
            section = ""
            current = None

            def flush():
                nonlocal current
                if current is not None:
                    items.append(current)
                    current = None

            for number, raw in enumerate(
                path.read_text(encoding="utf-8", errors="replace").splitlines(), 1
            ):
                line = raw.rstrip()
                heading = SECTION_RE.match(line)
                if heading:
                    flush()
                    section = heading.group(1).strip()
                    continue
                box = BOX_RE.match(line)
                if box:
                    flush()
                    current = {
                        "path": rel,
                        "line": number,
                        "text": box.group(1).strip(),
                        "group": section,
                    }
                    continue
                if line.startswith("- ["):
                    flush()
                    continue
                if line.lstrip().startswith("|"):
                    flush()
                    row = self._table_row(line)
                    if row is not None:
                        row.update({"path": rel, "line": number, "group": section})
                        items.append(row)
                    continue
                if current is not None and line.strip() and line[:1].isspace():
                    current["text"] += " " + line.strip()
                    continue
                if not line.strip():
                    flush()
            flush()

        return [
            Item(
                path=entry["path"],
                line=entry["line"],
                text=re.sub(r"\s+", " ", entry["text"]).strip(),
                body=re.sub(r"\s+", " ", entry.get("body") or entry["text"]).strip(),
                kind="open",
                group=entry["group"],
            )
            for entry in items
        ]

    def _table_row(self, line: str) -> dict | None:
        """A backlog row written as a table row rather than a checkbox.

        Structure only: which cell is the title, which row is a header or a
        separator. Whether a row is still live is the `done` decision below,
        and adapters can override it.
        """
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) < 3:
            return None
        if all(TABLE_SEPARATOR_RE.match(cell) for cell in cells if cell):
            return None
        first = cells[0]
        if first.lower().strip("*") in TABLE_HEADERS:
            return None

        title = cells[1] if len(cells) > 1 and cells[1] else first
        if title.startswith("~~") or not title:
            return None
        plain = re.sub(r"[*~`]", "", title).strip()
        body = " ".join(cell for cell in cells if cell)
        if self.done(body, plain):
            return None
        return {"text": "%s %s" % (first, plain) if first and first != plain else plain, "body": body}

    def done(self, row: str, title: str) -> bool:
        """Whether a backlog row describes closed work.

        A default, not a rule: `Done`/`Shipped` without any open word is the
        common way a backlog marks a row finished. An adapter that uses a
        status column, a label, or a separate archive overrides this.
        """
        lowered = row.lower()
        return bool(DONE_RE.search(lowered)) and not OPEN_RE.search(lowered)

    def sources(self, root: Path) -> list[Source]:
        detected = self.detected(root)
        claimed = self._claimed_paths(root, detected)
        excluded = self.excluded(root)
        archived = self.archived(root)
        # Only files the walk saw: a gitignored or skipped file is not a source.
        walked = detected.paths
        found = {}
        for pattern in SOURCE_GLOBS:
            for path in sorted(root.glob(pattern)):
                rel = path.relative_to(root).as_posix()
                if rel not in walked:
                    continue
                if rel in found or rel in claimed or rel in excluded or is_archived(rel, archived):
                    continue
                try:
                    if path.stat().st_size > MAX_SOURCE_BYTES:
                        continue
                    text = path.read_text(encoding="utf-8", errors="replace")
                except OSError:
                    continue
                if is_generated(text):
                    continue
                found[rel] = Source(path=rel, kind=_source_kind(rel), text=text)
        return list(found.values())

    def excluded(self, root: Path) -> set[str]:
        """Quoted evidence and tool notes: never an answer.

        Raw conversation competes with real docs if it is ranked, and citing it
        as guidance would turn "they wondered aloud" into "we decided". The
        repo-brief notes file is agent-facing intake, not product prose.
        """
        excluded = {NOTES_DOC}
        base = root / CAPTURE_DIR
        if base.is_dir():
            excluded.update(
                path.relative_to(root).as_posix() for path in base.rglob("*.md")
            )
        return excluded

    def canonical(self, root: Path) -> list[str]:
        detected = self.detected(root)
        wanted = [detected.index, detected.status, detected.changelog]
        wanted += detected.open_work[:1]
        if (root / WRITING_DOC).is_file():
            wanted.append(WRITING_DOC)
        return [rel for rel in wanted if rel]

    def usage_roots(self, root: Path) -> list[str]:
        return self.detected(root).source_roots

    def dated(self, root: Path) -> list[str]:
        status = self.detected(root).status
        return [status] if status else []

    def archived(self, root: Path) -> list[str]:
        return self.detected(root).archived


def _source_kind(rel: str) -> str:
    if rel.startswith("docs/") or rel.endswith(".md"):
        return "docs"
    if rel.startswith(("tools/", "scripts/")):
        return "tool"
    if rel.startswith(".github/"):
        return "build"
    if rel.startswith(("AGENTS.md", "rules.md", "CLAUDE.md")):
        return "rules"
    return "docs"
