"""Output shapes.

Two forms, both deliberately short. `brief` is what an agent should call first;
`full` exists for a human who wants the whole ranked set.
"""
from __future__ import annotations

import hashlib
import re
from pathlib import Path

GENERATED = "<!-- GENERATED by repo-brief. Do not edit by hand. -->"
STRUCTURE_RE = re.compile(r"<!-- structure: ([0-9a-f]+) -->")


def structure_digest(markdown: str) -> str:
    """Short fingerprint of everything except prose descriptions."""
    return hashlib.sha256(markdown.encode("utf-8")).hexdigest()[:12]


def stamp(markdown: str, digest: str) -> str:
    """Record the structure fingerprint in the map itself."""
    return markdown.replace(
        GENERATED, GENERATED + "\n<!-- structure: %s -->" % digest, 1
    )


def _truncate(text: str, width: int) -> str:
    text = " ".join(text.split())
    if len(text) <= width:
        return text
    return text[: width - 1].rstrip() + "…"


def _label(item: dict) -> str:
    """How to cite a record: its own id, or its filename when it has none.

    A decision directory gives each entry a filename (`D-041`). A single-file
    log does not, and printing the log's name for every row says nothing.
    """
    return item.get("label") or Path(item["path"]).stem


def _size(value) -> str:
    """A file or slice size a reader can compare at a glance."""
    try:
        size = int(value or 0)
    except (TypeError, ValueError):
        return ""
    if size >= 1024 * 1024:
        return "%.1f MB" % (size / (1024 * 1024))
    if size >= 1024:
        return "%.1f KB" % (size / 1024)
    return "%d B" % size


def _read_line(item: dict) -> str:
    """One line of the read plan: path, slice, cost, and why."""
    start = item.get("start") or item.get("line") or 1
    end = item.get("end") or start
    line = "  %s:%d-%d" % (item["path"], start, end)
    if item.get("bytes"):
        line += "  %s" % _size(item["bytes"])
    if item.get("truncated"):
        # One line over the slice cap, kept whole: a table row cut in half is
        # worse than a long line.
        line += "  (one long line)"
    if item.get("label"):
        line += "  # %s" % _truncate(item["label"], 40)
    if item.get("archived"):
        line += " (archived)"
    return line


def _facts_line(facts: dict) -> str:
    """One line pointing a context query at the fact tools."""
    tool = facts.get("tool") or "repo_facts"
    kind = facts.get("kind") or ""
    total = facts.get("total") or 0
    noun = "%s fact" % kind if kind else "fact"
    label = "%d %s" % (total, noun if total == 1 else noun + "s")
    matches = facts.get("matches") or []
    if matches:
        matched = facts.get("match_total") or len(matches)
        return "Facts: %s; %d %s, e.g. %s; `%s <words>` searches them." % (
            label,
            matched,
            "match" if matched == 1 else "matches",
            ", ".join(matches),
            tool,
        )
    return "Facts: %s; `%s <words>` searches them." % (label, tool)


def render_brief(context: dict) -> str:
    header = "Context: %s" % context["query"]
    if context.get("archived"):
        header += " (including archive)"
    lines = [header]

    decisions = context.get("decisions", [])
    if decisions:
        shown = ", ".join(
            "%s %s" % (_label(item), _truncate(item["text"], 60))
            for item in decisions[:2]
        )
        lines.append("Decisions: %s" % shown)

    open_work = context.get("open_work", [])
    if open_work:
        item = open_work[0]
        lines.append(
            "Open work: %s:%d %s"
            % (item["path"], item["line"], _truncate(item["text"], 110))
        )

    if context.get("facts"):
        lines.append(_facts_line(context["facts"]))

    plan = context.get("read_plan")
    if plan:
        budget = context.get("budget") or {}
        total = budget.get("bytes")
        lines.append("Read (%s):" % _size(total) if total else "Read:")
        lines.extend(_read_line(item) for item in plan)
    elif plan is None:
        # Older callers may build a context dict without a read plan.
        read = []
        seen = set()
        for item in context.get("sources", [])[:2]:
            if item["path"] in seen:
                continue
            seen.add(item["path"])
            read.append("%s:%d%s" % (item["path"], item["line"], " (archived)" if item.get("archived") else ""))
        for unit in context.get("units", []):
            # A doc can rank as both a source and a unit; cite it once, with its line.
            if unit["path"] in seen:
                continue
            seen.add(unit["path"])
            read.append(unit["path"] + (" (archived)" if unit.get("archived") else ""))
            if len(read) >= 5:
                break
        if read:
            lines.append("Read:")
            lines.extend("  %s" % path for path in read)

    also = context.get("also_matched") or []
    if also:
        lines.append("Also matched: %s" % ", ".join(also))

    # A brief that matches nothing must say what it looked for. The words are
    # the query's own, split the way the index splits a name, so a name it
    # failed to find is visible at a glance.
    if (
        not plan
        and not decisions
        and not open_work
        and not context.get("usage")
        and not context.get("sources")
        and not context.get("units")
    ):
        searched = context.get("tokens") or []
        if searched:
            lines.append("No match for: %s." % ", ".join(searched))

    usage = context.get("usage", [])
    if usage:
        lines.append("Hits:")
        for item in usage[:2]:
            lines.append("  %s:%d %s" % (item["path"], item["line"], _truncate(item["snippet"], 130)))

    tests = context.get("tests", [])
    if tests:
        lines.append("Tests: %s" % ", ".join(Path(path).name for path in tests[:5]))

    return "\n".join(lines)


def render_full(context: dict) -> str:
    header = "Query: %s" % context["query"]
    if context.get("archived"):
        header += " (including archive)"
    lines = [header, "Tokens: %s" % ", ".join(context["tokens"]), ""]
    if context.get("facts"):
        lines.extend([_facts_line(context["facts"]), ""])

    lines.append("Decisions")
    if context["decisions"]:
        for item in context["decisions"]:
            group = " [%s]" % item["group"] if item.get("group") else ""
            lines.append(
                "  %s%s  %s:%d"
                % (_label(item), group, item["path"], item["line"])
            )
            lines.append("    %s" % item["text"])
    else:
        lines.append("  (none matched)")
    lines.append("")

    lines.append("Open work")
    if context.get("open_work"):
        for item in context["open_work"]:
            lines.append(
                "  %s:%d [%s] %s"
                % (item["path"], item["line"], item.get("group") or "open", item["text"])
            )
    else:
        lines.append("  (none matched)")
    lines.append("")

    lines.append("Sources")
    if context.get("sources"):
        for item in context["sources"]:
            marker = " [archived]" if item.get("archived") else ""
            lines.append(
                "  %s:%d [%s]%s %s" % (item["path"], item["line"], item["kind"], marker, item["snippet"])
            )
    else:
        lines.append("  (none matched — try broader terms)")
    lines.append("")

    lines.append("Files")
    if context["units"]:
        source_paths = {item["path"] for item in context.get("sources", [])}
        shown = False
        for unit in context["units"]:
            if unit["path"] in source_paths:
                continue
            shown = True
            details = []
            if unit.get("class_name"):
                details.append("class %s" % unit["class_name"])
            if unit.get("extends"):
                details.append("extends %s" % unit["extends"])
            suffix = " (%s)" % ", ".join(details) if details else ""
            marker = " [archived]" if unit.get("archived") else ""
            lines.append("  %s%s%s" % (unit["path"], marker, suffix))
            for symbol in unit.get("symbols", []):
                lines.append(
                    "    %s %s :%s" % (symbol.get("kind"), symbol.get("name"), symbol.get("line"))
                )
        if not shown:
            lines.append("  (no matching file — try broader terms)")
    else:
        lines.append("  (no matching file — try broader terms)")
    lines.append("")

    lines.append("Tests")
    if context["tests"]:
        lines.extend("  %s" % path for path in context["tests"])
    else:
        lines.append("  (none mapped)")
    lines.append("")

    lines.append("Usage hits")
    if context.get("usage"):
        for item in context["usage"]:
            lines.append("  %s:%d %s" % (item["path"], item["line"], item["snippet"]))
    else:
        lines.append("  (none matched)")
    lines.append("")

    lines.append("Resources / scenes")
    if context.get("resources"):
        lines.extend("  %s" % path for path in context["resources"])
    else:
        lines.append("  (none mapped)")

    return "\n".join(lines)


def render_map(
    detected,
    units,
    decisions,
    open_work,
    adapter_name: str,
    edges=None,
    coverage=None,
    descriptions: bool = True,
) -> str:
    """The committed map: the where layer.

    `descriptions=False` renders the same map with every docstring-derived
    "declares" cell blanked and every decision and open-work line number
    dropped. That variant is what `index --check` hashes: a changed comment, or
    a paragraph that pushes a decision down its log, must not make the map
    stale, but a changed file or a new decision must.
    """
    edges = edges or []
    coverage = coverage or {}
    lines = [
        "<!-- GENERATED by repo-brief. Do not edit by hand. -->",
        "",
        "# Repo map",
        "",
        "Generated by `repo-brief index`. Adapter: `%s`." % adapter_name,
        "",
        "## Detected",
        "",
    ]
    for language, count in detected.languages[:8]:
        lines.append("- %s — %d files" % (language, count))
    if detected.manifests:
        lines.append("- manifests: %s" % ", ".join("`%s`" % p for p in detected.manifests))
    if detected.decisions_dir:
        lines.append("- decisions: `%s/`" % detected.decisions_dir)
    if detected.decisions_file:
        lines.append("- decisions: `%s`" % detected.decisions_file)
    if detected.status:
        lines.append("- status: `%s`" % detected.status)
    if detected.open_work:
        lines.append("- open work: %s" % ", ".join("`%s`" % p for p in detected.open_work))
    if detected.autoloads:
        lines.append("- autoloads: %d singletons" % len(detected.autoloads))
    if edges:
        lines.append("- dependency edges: %d" % len(edges))
    lines.append("")

    by_dir: dict[str, list] = {}
    other: dict[str, int] = {}
    archived_units = []
    for unit in units:
        if unit.kind == "archive":
            archived_units.append(unit)
            continue
        folder = str(Path(unit.path).parent)
        if unit.fields:
            by_dir.setdefault(folder, []).append(unit)
        else:
            other[folder] = other.get(folder, 0) + 1

    lines.append("## Files")
    lines.append("")
    for folder in sorted(set(by_dir) | set(other)):
        if folder in by_dir:
            lines.append("### `%s/`" % folder)
            lines.append("")
            lines.append("| file | kind | declares | tests |")
            lines.append("|---|---|---|---|")
            for unit in sorted(by_dir[folder], key=lambda u: u.path):
                name = Path(unit.path).name
                declares = _declares(unit, descriptions)
                tests = _tests_for_unit(coverage.get(unit.path, []))
                lines.append("| `%s` | %s | %s | %s |" % (name, unit.kind, declares or "—", tests or "—"))
            lines.append("")
        if folder in other:
            lines.append("*%d other file(s) in `%s/`*" % (other[folder], folder))
            lines.append("")

    scenes = [unit for unit in units if unit.kind in ("scene", "resource") and unit.fields.get("scripts")]
    if scenes:
        lines.append("## Scenes and resources")
        lines.append("")
        lines.append("| file | scripts |")
        lines.append("|---|---|")
        for unit in sorted(scenes, key=lambda u: u.path):
            scripts = ", ".join("`%s`" % Path(path).name for path in unit.fields["scripts"])
            lines.append("| `%s` | %s |" % (unit.path, scripts))
        lines.append("")

    if detected.autoloads:
        lines.append("## Autoloads")
        lines.append("")
        lines.append("| name | script | used by |")
        lines.append("|---|---|---|")
        users: dict[str, int] = {}
        for edge in edges:
            users[edge.target] = users.get(edge.target, 0) + 1
        for name in sorted(detected.autoloads):
            path = detected.autoloads[name]
            lines.append("| `%s` | `%s` | %d |" % (name, path, users.get(path, 0)))
        lines.append("")

    if archived_units:
        lines.append("## Archived")
        lines.append("")
        lines.append(
            "Kept so old links resolve. `context` ignores these unless asked with `--archived`."
        )
        lines.append("")
        for unit in sorted(archived_units, key=lambda u: u.path):
            lines.append("- `%s`" % unit.path)
        lines.append("")

    lines.append("## Decisions")
    lines.append("")
    if decisions:
        for item in decisions:
            stem = Path(item.path).stem
            prefix = "" if stem == (item.label or stem) else "%s — " % item.label
            lines.append(
                "- `%s` — %s%s%s"
                % (_where(item, descriptions), prefix, item.text, " (%s)" % item.group if item.group else "")
            )
    else:
        lines.append("(none found)")
    lines.append("")

    lines.append("## Open work")
    lines.append("")
    if open_work:
        for item in open_work:
            lines.append("- `%s` [%s] %s" % (_where(item, descriptions), item.group or "open", item.text))
    else:
        lines.append("(none found)")
    lines.append("")

    return "\n".join(lines)


def _where(item, positions: bool = True) -> str:
    """`path:line`, or the path alone when rendering structure.

    A line number says where a record sits, not what the repo decided. It goes
    stale whenever the file above it grows, and refreshes on the next `index`.
    """
    return "%s:%d" % (item.path, item.line) if positions else item.path


def _declares(unit, descriptions: bool = True) -> str:
    class_name = unit.fields.get("class_name") or ""
    # Implemented interfaces sit beside the parent: `TheWorldImpl` → `TheWorld`
    # is how a class names the interface it implements.
    parents = [unit.fields.get("extends") or ""] + list(unit.fields.get("implements") or [])
    parents = ["`%s`" % parent for parent in parents if parent]
    if class_name and parents:
        return "`%s` → %s" % (class_name, ", ".join(parents))
    if class_name:
        return "`%s`" % class_name
    if not descriptions:
        return ""
    description = unit.fields.get("description") or ""
    return _truncate(str(description), 70)


def _tests_for_unit(tests: list) -> str:
    if not tests:
        return ""
    names = [Path(path).name for path in tests]
    if len(names) > 2:
        return "%s +%d" % (", ".join(names[:2]), len(names) - 2)
    return ", ".join(names)
